"""Interactive and non-interactive NAS deployment for Personal Agent."""

from __future__ import annotations

import argparse
import getpass
import os
import secrets
import shutil
import subprocess
import sys
import time
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

PLACEHOLDERS = {
    "",
    "replace-with-a-strong-password",
    "replace-with-a-long-random-secret",
    "replace-with-an-internal-random-token",
}


def parse_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
            value = value[1:-1]
        values[key.strip()] = value
    return values


def write_env(path: Path, values: dict[str, str]) -> None:
    lines = [
        "# Generated by scripts/deploy.py. Keep this file private.",
        *(
            f"{key}={values[key]}"
            for key in [
                "AGENT_ADMIN_USERNAME",
                "AGENT_ADMIN_PASSWORD",
                "AGENT_SECRET_KEY",
                "AGENT_EXECUTOR_TOKEN",
                "AGENT_DATA_DIR",
                "COMPOSE_PROJECT_NAME",
                "AGENT_AI_PROVIDER",
                "AGENT_LLM_PROVIDER",
                "AGENT_ASR_PROVIDER",
                "AGENT_TTS_PROVIDER",
                "AGENT_MIMO_API_KEY",
                "AGENT_MIMO_BASE_URL",
                "AGENT_MIMO_LLM_MODEL",
                "AGENT_MIMO_ASR_MODEL",
                "AGENT_MIMO_TTS_MODEL",
                "AGENT_MIMO_VOICE",
                "AGENT_MINIMAX_API_KEY",
                "AGENT_MINIMAX_REGION",
                "AGENT_MINIMAX_BASE_URL",
                "AGENT_MINIMAX_LLM_MODEL",
                "AGENT_MINIMAX_ASR_MODEL",
                "AGENT_MINIMAX_TTS_MODEL",
                "AGENT_MINIMAX_VOICE",
                "AGENT_MINIMAX_REASONING_EFFORT",
                "AGENT_MAX_ASYNC_TASKS",
                "AGENT_MAX_THREAD_WORKERS",
                "AGENT_MAX_BROWSER_SESSIONS",
                "AGENT_TASK_TIMEOUT_SECONDS",
                "AGENT_EXECUTOR_BASE_URL",
                "SERVER_PORT",
                "SERVER_BIND_IP",
            ]
            if key in values
        ),
        "",
    ]
    temporary = path.with_suffix(".tmp")
    temporary.write_text("\n".join(lines), encoding="utf-8")
    temporary.chmod(0o600)
    temporary.replace(path)


def _generated(value: str | None) -> bool:
    return value is None or value in PLACEHOLDERS


def _credential(
    args: argparse.Namespace,
    values: dict[str, str],
    provider: str,
    input_key: str,
    output_key: str,
) -> None:
    supplied = getattr(args, input_key) or os.getenv(output_key)
    if supplied:
        values[output_key] = supplied
    if not _generated(values.get(output_key)):
        return
    if args.yes:
        raise SystemExit(f"缺少 {output_key}：通过环境变量或部署参数提供")
    values[output_key] = getpass.getpass(f"请输入 {provider} API Key：").strip()
    if not values[output_key]:
        raise SystemExit(f"{output_key} 不能为空")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Personal Agent NAS 一键部署")
    parser.add_argument("--project-dir", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--provider", choices=["mimo", "minimax", "hybrid"])
    parser.add_argument("--mimo-key", dest="mimo_key")
    parser.add_argument("--minimax-key", dest="minimax_key")
    parser.add_argument("--minimax-region", choices=["global", "cn"], default=None)
    parser.add_argument("--admin-username", default=None)
    parser.add_argument("--admin-password", default=None)
    parser.add_argument("--port", type=int, default=None)
    parser.add_argument("--yes", action="store_true", help="无人值守，不询问")
    parser.add_argument("--no-start", action="store_true", help="只生成 .env")
    parser.add_argument("--no-watchdog", action="store_true", help="不启用健康看门狗")
    return parser


def prepare_values(args: argparse.Namespace, values: dict[str, str]) -> tuple[bool, str]:
    provider = args.provider or values.get("AGENT_AI_PROVIDER", "mimo")
    if provider not in {"mimo", "minimax", "hybrid"}:
        raise SystemExit("AGENT_AI_PROVIDER 仅支持 mimo、minimax、hybrid")

    values["AGENT_ADMIN_USERNAME"] = args.admin_username or values.get(
        "AGENT_ADMIN_USERNAME", "admin"
    )
    generated_admin = False
    if args.admin_password:
        values["AGENT_ADMIN_PASSWORD"] = args.admin_password
    elif _generated(values.get("AGENT_ADMIN_PASSWORD")):
        values["AGENT_ADMIN_PASSWORD"] = secrets.token_urlsafe(14)
        generated_admin = True
    for key in ("AGENT_SECRET_KEY", "AGENT_EXECUTOR_TOKEN"):
        if _generated(values.get(key)):
            values[key] = secrets.token_urlsafe(48)
    values["AGENT_DATA_DIR"] = values.get("AGENT_DATA_DIR", "./data")
    values["SERVER_PORT"] = str(args.port or int(values.get("SERVER_PORT", "8080")))
    values["SERVER_BIND_IP"] = values.get("SERVER_BIND_IP", "0.0.0.0")
    values["COMPOSE_PROJECT_NAME"] = values.get("COMPOSE_PROJECT_NAME", "personal-agent")
    if args.minimax_region:
        values["AGENT_MINIMAX_REGION"] = args.minimax_region

    # Remove old overrides when switching back to a single provider.
    for key in ("AGENT_LLM_PROVIDER", "AGENT_ASR_PROVIDER", "AGENT_TTS_PROVIDER"):
        values.pop(key, None)
    if provider == "hybrid":
        values.update(
            AGENT_AI_PROVIDER="mimo",
            AGENT_LLM_PROVIDER="minimax",
            AGENT_ASR_PROVIDER="mimo",
            AGENT_TTS_PROVIDER="mimo",
        )
        _credential(args, values, "MiniMax", "minimax_key", "AGENT_MINIMAX_API_KEY")
        _credential(args, values, "MiMo", "mimo_key", "AGENT_MIMO_API_KEY")
    else:
        values["AGENT_AI_PROVIDER"] = provider
        _credential(
            args, values, provider.upper(), f"{provider}_key", f"AGENT_{provider.upper()}_API_KEY"
        )
    return generated_admin, provider


def wait_health(port: int, timeout_seconds: int = 120) -> None:
    url = f"http://127.0.0.1:{port}/healthz"
    deadline = time.monotonic() + timeout_seconds
    while time.monotonic() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=3) as response:
                if response.status == 200:
                    return
        except OSError:
            pass
        time.sleep(2)
    raise SystemExit(f"健康检查超时：{url}；请运行 docker compose logs --tail 100 server")


def main() -> None:
    args = build_parser().parse_args()
    root = args.project_dir.resolve()
    if not (root / "docker-compose.yml").exists() or not (root / ".env.example").exists():
        raise SystemExit(f"项目目录缺少 docker-compose.yml 或 .env.example：{root}")
    env_path = root / ".env"
    values = parse_env(root / ".env.example")
    values.update(parse_env(env_path))
    generated_admin, provider = prepare_values(args, values)
    if env_path.exists():
        stamp = datetime.now(UTC).strftime("%Y%m%d%H%M%S")
        shutil.copy2(env_path, root / f".env.backup-{stamp}")
    write_env(env_path, values)
    print(f"配置已写入：{env_path}（权限 0600）")
    print(f"Provider：{provider}")
    if args.no_start:
        print("已生成配置，未启动容器。")
        return

    if not shutil.which("docker"):
        raise SystemExit("未找到 Docker CLI；配置已生成，安装 Docker 后重新运行此命令")
    subprocess.run(["docker", "compose", "version"], cwd=root, check=True, capture_output=True)
    command = ["docker", "compose"]
    if not args.no_watchdog:
        command.extend(["--profile", "watchdog"])
    command.extend(["up", "-d"])
    if not args.no_build:
        command.append("--build")
    subprocess.run(command, cwd=root, check=True)
    port = int(values["SERVER_PORT"])
    wait_health(port)
    print(f"部署完成：http://NAS_IP:{port}")
    print(f"App Base URL：http://NAS_IP:{port}/api/v1")
    print(f"管理员：{values['AGENT_ADMIN_USERNAME']}")
    if generated_admin:
        print(f"首次生成的管理员密码（仅本次显示）：{values['AGENT_ADMIN_PASSWORD']}")


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as exc:
        sys.exit(exc.returncode or 1)
